function chatLocal(c, text) {
  const t = text.toLowerCase().replace(/ё/g, "е");
  if (/^(привет|здравств|добрый|добрая|хай|здорово)/.test(t)) return chatPick(c.hi);
  if (/(до свидан|прощай|пока$|всего доброго)/.test(t)) return chatPick(c.bye);
  let best = null, top = 0;
  c.it.forEach(i => { const n = i.k.filter(k => t.includes(k)).length; if (n > top) { top = n; best = i; } });
  if (!best) return chatPick(c.fb);
  best.u = best.u || [];
  let free = best.r.filter((_, j) => !best.u.includes(j));
  if (!free.length) { best.u = []; free = best.r; }
  const idx = best.r.indexOf(chatPick(free));
  best.u.push(idx);
  return best.r[idx];
}
async function askServer(c, history) {
  // Подключение настоящего ИИ: ваш сервер принимает {character, role, messages}
  // и возвращает {reply: "..."}. Ключ API храните только на сервере.
  const r = await fetch(CHAT_API, {method: "POST", headers: {"Content-Type": "application/json"},
    body: JSON.stringify({character: c.n, role: c.r, messages: history})});
  return (await r.json()).reply;
}
async function chatSend(text) {
  if (chatBusy) return;
  chatBusy = true;
  const c = chatChars[chatCur];
  chatAdd("me", text);
  chatLog.push({role: "user", content: text});
  const typing = chatAdd("bot", c.n + " печатает…", "typing");
  let reply;
  try { reply = CHAT_API ? await askServer(c, chatLog) : null; } catch (e) { reply = null; }
  if (!reply) { reply = chatLocal(c, text); await new Promise(r => setTimeout(r, 600 + Math.random() * 700)); }
  typing.remove();
  chatAdd("bot", reply);
  chatLog.push({role: "assistant", content: reply});
  chatBusy = false;
}

